// Firebase is optional at build time: without google-services.json the app still
// builds and runs in local-only mode (no cloud account, sync or push).
val firebaseConfigured = file("google-services.json").exists()
if (firebaseConfigured) {
    apply(plugin = libs.plugins.google.services.get().pluginId)
    apply(plugin = libs.plugins.firebase.crashlytics.get().pluginId)
}

// Release signing reads keystore.properties (git-ignored). Without it, release builds are unsigned.
val keystoreProps = Properties().apply {
    val file = rootProject.file("keystore.properties")
    if (file.exists()) file.inputStream().use { load(it) }
}

// Address of the coach service (server/coach-worker). Set coach.url in local.properties, or pass
// -PcoachUrl=... for a one-off build. Left empty, the coach screen explains it is not set up.
val localProps = Properties().apply {
    val file = rootProject.file("local.properties")
    if (file.exists()) file.inputStream().use { load(it) }
}
val coachUrl = (findProperty("coachUrl") as String?) ?: localProps.getProperty("coach.url", "")

// -PfirebaseEmulator=true points debug builds at the local Firebase Emulator Suite.
val useFirebaseEmulator = (findProperty("firebaseEmulator") as String?)?.toBoolean() ?: false

android {
    namespace = "app.paisapilot"
    compileSdk = 36

    defaultConfig {
        applicationId = "app.paisapilot"
        minSdk = 26
        targetSdk = 36
        versionCode = 1
        versionName = "1.0.0"
        testInstrumentationRunner = "androidx.test.runner.AndroidJUnitRunner"
        buildConfigField("boolean", "FIREBASE_EMULATOR", "false")
        buildConfigField("String", "COACH_URL", "\"$coachUrl\"")
    }

    signingConfigs {
        if (keystoreProps.containsKey("storeFile")) {
            create("release") {
                storeFile = rootProject.file(keystoreProps.getProperty("storeFile"))
                storePassword = keystoreProps.getProperty("storePassword")
                keyAlias = keystoreProps.getProperty("keyAlias")
                keyPassword = keystoreProps.getProperty("keyPassword")
            }
        }
    }

    buildTypes {
        debug {
            buildConfigField("boolean", "FIREBASE_EMULATOR", useFirebaseEmulator.toString())
        }
        release {
            signingConfig = signingConfigs.findByName("release")
            isMinifyEnabled = true
            isShrinkResources = true
            proguardFiles(getDefaultProguardFile("proguard-android-optimize.txt"), "proguard-rules.pro")
        }
    }

    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }

    buildFeatures {
        compose = true
        buildConfig = true
    }

    packaging {
        resources.excludes += "/META-INF/{AL2.0,LGPL2.1}"
    }
}

